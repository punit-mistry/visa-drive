/** The minimal shape the marketing surface reads off a visa product. */
export interface CatalogueProduct {
  _id: string;
  slug: string;
  destinationSlug: string;
  name: string;
  category: string;
  visaType: string;
  shortDescription: string;
  entryType: string;
  validityDays?: number;
  maxStayDays?: number;
  processingTimeMinDays?: number;
  processingTimeMaxDays?: number;
  processingTimeNote?: string;
  currency: string;
  governmentFee: number;
  serviceFee: number;
  promoPrice?: number;
  promoLabel?: string;
  promoEndsAt?: number;
  paymentMode: string;
  isDemoContent: boolean;
  displayOrder: number;
}

/**
 * True when a promo is configured and has not passed its end date. Shared so
 * the badge, the headline price and the struck-through standard price can
 * never disagree about whether a promo is live.
 */
export function hasActivePromo(
  product: Pick<CatalogueProduct, "promoPrice" | "promoEndsAt">,
  now = Date.now(),
): boolean {
  return (
    typeof product.promoPrice === "number" &&
    (product.promoEndsAt === undefined || product.promoEndsAt > now)
  );
}

/**
 * The advertised per-traveller price, or `null` when the catalogue carries no
 * usable figure. A product priced at zero across both fees has not been
 * configured, so it is treated as absent rather than shown as "free".
 */
export function productPrice(
  product: Pick<
    CatalogueProduct,
    "governmentFee" | "serviceFee" | "promoPrice" | "promoEndsAt"
  >,
  now = Date.now(),
): number | null {
  const promoActive =
    hasActivePromo(product, now) && product.promoPrice! >= 0;

  const value = promoActive
    ? product.promoPrice!
    : (product.governmentFee ?? 0) + (product.serviceFee ?? 0);

  return value > 0 ? value : null;
}

/** The standard price, shown struck through only when a promo is really on. */
export function standardPrice(
  product: Pick<
    CatalogueProduct,
    "governmentFee" | "serviceFee" | "promoPrice" | "promoEndsAt"
  >,
  now = Date.now(),
): number | null {
  const promoActive = hasActivePromo(product, now);
  if (!promoActive) return null;
  const standard = (product.governmentFee ?? 0) + (product.serviceFee ?? 0);
  return standard > 0 && standard > product.promoPrice! ? standard : null;
}

/** `null` when the admin has not recorded a processing window. */
export function productProcessingTime(
  product: Pick<
    CatalogueProduct,
    "processingTimeMinDays" | "processingTimeMaxDays" | "processingTimeNote"
  >,
): string | null {
  return formatProcessingTime(
    product.processingTimeMinDays,
    product.processingTimeMaxDays,
    product.processingTimeNote,
  );
}

/**
 * The longest validity across a destination's products, e.g. "90 days" or
 * "10 years". Whole-year values read as years; anything else stays in days.
 */
export function longestValidity(
  products: Array<Pick<CatalogueProduct, "validityDays">>,
): string | null {
  const days = products
    .map((product) => product.validityDays)
    .filter((value): value is number => typeof value === "number" && value > 0);

  if (days.length === 0) return null;

  const max = Math.max(...days);
  if (max >= 365 && max % 365 === 0) {
    const years = max / 365;
    return `${years} year${years > 1 ? "s" : ""}`;
  }
  return `${max} days`;
}

/** Distinct categories across a destination's products, in catalogue order. */
export function distinctCategories(products: Array<{ category: string }>): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const product of products) {
    if (seen.has(product.category)) continue;
    seen.add(product.category);
    out.push(product.category);
  }
  return out;
}

/** The shortest recorded processing window across a set of products. */
export function fastestProcessingTime(
  products: Array<
    Pick<
      CatalogueProduct,
      "processingTimeMinDays" | "processingTimeMaxDays" | "processingTimeNote"
    >
  >,
): string | null {
  const withDays = products.filter(
    (p) => p.processingTimeMinDays != null || p.processingTimeMaxDays != null,
  );
  if (withDays.length === 0) return null;

  const best = withDays.reduce((acc, p) => {
    const a = acc.processingTimeMinDays ?? acc.processingTimeMaxDays ?? Infinity;
    const b = p.processingTimeMinDays ?? p.processingTimeMaxDays ?? Infinity;
    return b < a ? p : acc;
  });

  return formatProcessingTime(
    best.processingTimeMinDays,
    best.processingTimeMaxDays,
    // A free-text note belongs to its own product and should not be reused as
    // a summary for the whole destination.
    null,
  );
}
